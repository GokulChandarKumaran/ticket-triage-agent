ROOT = Path(__file__).resolve().parent.parent


def load_tickets() -> list[dict]:
    return json.loads((DATA_DIR / "tickets.json").read_text(encoding="utf-8"))


def new_run_dir(label: str = "run") -> Path:
    d = ROOT / "outputs" / f"{label}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    d.mkdir(parents=True, exist_ok=True)
    return d


def make_client():
    import anthropic  # imported lazily so the offline tests do not need credentials

    return anthropic.Anthropic()


def triage_and_verify(ticket: dict, client, out_dir: Path, fail_tools=(), verbose: bool = True,
                      label: str | None = None) -> dict:
    before = file_sha256()
    result, ctx = run_ticket(ticket, client, out_dir, fail_tools=set(fail_tools),
                             on_event=print_event if verbose else None)
    checks = verify(result, ctx, before)
    expected = score_against_expected(result.final_note, ticket["expected"]) if "expected" in ticket else None
    if verbose:
        print_checks(checks)
        if expected:
            print_checks([expected], header="EVAL (vs. hand-labelled expectation)")
    record = {
        "label": label or ticket["ticket_id"],
        "ticket_id": ticket["ticket_id"],
        "case": ticket.get("expected", {}).get("case", ""),
        "fail_tools": sorted(fail_tools),
        "status": result.status,
        "steps": result.steps,
        "tools_used": [e["tool"] for e in result.events if e["type"] == "tool_call"],
        "tool_errors": sum(1 for e in result.events if e["type"] == "tool_result" and e["is_error"]),
        "final_note": result.final_note,
        "verified": all(c.passed for c in checks),
        "checks": [c.__dict__ for c in checks],
        "expected_check": expected.__dict__ if expected else None,
        "usage": result.usage,
        "served_by": result.served_by,
    }
    trace_path = out_dir / "traces" / f"{record['label']}.json"
    trace_path.parent.mkdir(parents=True, exist_ok=True)
    trace_path.write_text(json.dumps({**record, "events": result.events}, indent=2, default=str), encoding="utf-8")
    return record


def write_pm_notes(records: list[dict], out_dir: Path) -> Path:
    lines = ["# Next-action notes for the product manager", "",
             "Generated by the triage agent. Drafts and proposed tasks are in this folder; nothing was sent.", ""]
    for r in records:
        n = r["final_note"]
        lines.append(f"## {r['label']}  -  {'VERIFIED' if r['verified'] else 'NOT VERIFIED'}")
        if n is None:
            lines += [f"No note (run status: {r['status']}). Needs manual triage.", ""]
            continue
        lines += [f"- **Action:** {n['action']}   **Priority:** {n['priority']}",
                  f"- **Evidence:** {', '.join(n['evidence_ids']) or 'none'}",
                  f"- **Note:** {n['note']}"]
        if n["draft_reply"]:
            lines.append(f"- **Draft reply (not sent):** {n['draft_reply']}")
        failed = [c for c in r["checks"] if not c["passed"]]
        if failed:
            lines.append("- **Verifier failures:** " + "; ".join(f"{c['name']}: {c['detail']}" for c in failed))
        lines.append("")
    path = out_dir / "pm_notes.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
